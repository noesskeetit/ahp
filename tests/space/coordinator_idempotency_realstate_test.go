//go:build state_integration

package space_test

import (
	"encoding/json"
	"strings"
	"testing"
	"time"

	"github.com/ahp-platform/ahp/internal/space"
	"github.com/ahp-platform/ahp/pkg/contracts"
)

// TestStateAPI_StreamEventIdempotency proves, against the REAL State service
// over PostgreSQL (accepted 461aa2ce), the exact stream-event idempotency
// contract that iv finding #74 requires the Core loop to honor. The offline
// MemDurabilitySink models these semantics; internal/space/durability.go points
// at THIS file as the authoritative-store validation, so it must exist and run:
//
//   - keys generated by the canonical space.StepKey(loopID, step) are distinct
//     per step, so a multi-step loop never collides with itself (the #74 bug
//     class: a constant key rejects every step after the first);
//   - re-appending a key with the SAME (kind,payload) is a deduped replay: no new
//     event, identical id + sequence (the safe retried emit);
//   - re-appending a key bound to a DIFFERENT payload is rejected with
//     KEY_REUSE_MISMATCH, and the rejection is PERMANENT (a later retry of the
//     same conflicting key fails again) while the original body stays unchanged;
//   - space.StepFingerprint is a faithful content digest: identical bodies hash
//     equal (so the replay is recognized), distinct bodies hash distinct (so the
//     reuse is detected). This is the same (kind,payload) digest State binds to
//     the key in internal/state/events.go AppendStream.
func TestStateAPI_StreamEventIdempotency(t *testing.T) {
	e := cNewEnv(t)
	ctx := e.ctx

	human := e.signTask(t, "task-"+contracts.NewID())
	th, err := e.client.CreateThread(ctx, human, contracts.Scope{}, "ctx-"+contracts.NewID(), "rs-idem-thread")
	if err != nil {
		t.Fatalf("CreateThread: %v", err)
	}
	if _, err := e.client.CreateRun(ctx, human, th.ID, "rs-idem-run", json.RawMessage(`{"type":"turn","n":1}`), ""); err != nil {
		t.Fatalf("CreateRun: %v", err)
	}
	claim, err := e.client.ClaimRun(ctx, "", "w1", 120*time.Second)
	if err != nil || claim.Lease == nil {
		t.Fatalf("ClaimRun: %v", err)
	}
	fence := space.Fence{RunID: claim.Lease.Run.ID, Worker: "w1", Epoch: claim.Lease.Epoch}
	tok := claim.TaskToken
	loopID := fence.RunID

	k0 := space.StepKey(loopID, 0)
	k1 := space.StepKey(loopID, 1)
	if k0 == k1 {
		t.Fatalf("StepKey collision between step 0 and 1: %q", k0)
	}

	bodyA := json.RawMessage(`{"step":"a","tool":"emil.delegate","artifact":"revenue.txt"}`)
	bodyB := json.RawMessage(`{"step":"b","tool":"emil.delegate","artifact":"other.txt"}`)

	// 1) First durable emission of step 0 creates a sequenced event.
	ev0, err := e.client.AppendStream(ctx, tok, th.ID, fence.RunID, fence.Worker, fence.Epoch, k0, "tool", bodyA)
	if err != nil {
		t.Fatalf("AppendStream step0: %v", err)
	}
	if ev0.Key != k0 || ev0.Sequence < 1 {
		t.Fatalf("unexpected step0 event: %+v", ev0)
	}

	// 2) Retry of step 0 with the SAME body dedupes: identical id + sequence,
	//    and the thread stream does NOT grow.
	again, err := e.client.AppendStream(ctx, tok, th.ID, fence.RunID, fence.Worker, fence.Epoch, k0, "tool", bodyA)
	if err != nil {
		t.Fatalf("replay of step0 must not error: %v", err)
	}
	if again.ID != ev0.ID || again.Sequence != ev0.Sequence {
		t.Fatalf("replay not idempotent: first=%+v replay=%+v", ev0, again)
	}
	evs, err := e.client.ReadStream(ctx, tok, th.ID, 0, 100)
	if err != nil {
		t.Fatalf("ReadStream: %v", err)
	}
	if len(evs) != 1 {
		t.Fatalf("replay grew the stream: %d events, want 1", len(evs))
	}

	// 3) Reuse of step 0's key with a DIFFERENT body is rejected with
	//    KEY_REUSE_MISMATCH.
	if _, err := e.client.AppendStream(ctx, tok, th.ID, fence.RunID, fence.Worker, fence.Epoch, k0, "tool", bodyB); err == nil {
		t.Fatal("key reuse with a different body must be rejected")
	} else if !strings.Contains(err.Error(), contracts.ErrKeyReuse) {
		t.Fatalf("want %s, got %v", contracts.ErrKeyReuse, err)
	}

	// 4) The rejection is PERMANENT: a later retry of the same conflicting key
	//    still fails, and the original body is preserved byte-for-byte.
	if _, err := e.client.AppendStream(ctx, tok, th.ID, fence.RunID, fence.Worker, fence.Epoch, k0, "tool", bodyB); err == nil || !strings.Contains(err.Error(), contracts.ErrKeyReuse) {
		t.Fatalf("key reuse must be permanently rejected, got %v", err)
	}
	evs, _ = e.client.ReadStream(ctx, tok, th.ID, 0, 100)
	if len(evs) != 1 || !sameJSONBytes(t, evs[0].Payload, bodyA) {
		t.Fatalf("a rejected reuse mutated the original step0 body: %+v", evs)
	}

	// 5) A distinct step key (step 1) lands as a NEW, next-sequenced event:
	//    per-step keys keep a multi-step loop from colliding with itself.
	ev1, err := e.client.AppendStream(ctx, tok, th.ID, fence.RunID, fence.Worker, fence.Epoch, k1, "tool", bodyB)
	if err != nil {
		t.Fatalf("AppendStream step1 must not collide with step0: %v", err)
	}
	if ev1.Sequence != ev0.Sequence+1 {
		t.Fatalf("step1 not the next sequence: got %d want %d", ev1.Sequence, ev0.Sequence+1)
	}

	// 6) StepFingerprint is a faithful content digest: same body -> same digest,
	//    different body -> different digest. This is precisely what makes State's
	//    same-key replay-vs-reuse decision correct for the Core loop's emissions.
	fpA, err := space.StepFingerprint("tool", bodyA)
	if err != nil {
		t.Fatalf("StepFingerprint(bodyA): %v", err)
	}
	fpA2, _ := space.StepFingerprint("tool", bodyA)
	fpB, _ := space.StepFingerprint("tool", bodyB)
	if fpA == "" || fpA != fpA2 {
		t.Fatalf("StepFingerprint not deterministic: %q vs %q", fpA, fpA2)
	}
	if fpA == fpB {
		t.Fatalf("StepFingerprint collided on distinct bodies: %q", fpA)
	}

	t.Logf("stream-event idempotency over REAL State: step0 seq=%d id=%s replay=dedup(same id) reuse=%s(permanent) step1 seq=%d fingerprint=%s...",
		ev0.Sequence, ev0.ID, contracts.ErrKeyReuse, ev1.Sequence, fpA[:8])
}
