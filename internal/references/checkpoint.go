package references

import (
	"context"
	"slices"

	"github.com/ahp-platform/ahp/pkg/contracts"
	"github.com/ahp-platform/ahp/pkg/labels"
)

// CheckpointArtifact is the immutable identity that State asks the artifact
// owner to retain. Mutable grant labels never participate in that identity.
type CheckpointArtifact struct {
	ID         string     `json:"id"`
	Tenant     string     `json:"tenant"`
	Deployment string     `json:"deployment"`
	Subject    string     `json:"subject"`
	ContextID  string     `json:"context_id"`
	TaskID     string     `json:"task_id"`
	Version    string     `json:"version"`
	SHA256     string     `json:"sha256"`
	Size       int64      `json:"size"`
	Labels     labels.Set `json:"labels"`
}

// Equal compares the exact stored descriptor, with label collections treated
// as sets. Live grant/effective labels are deliberately absent from this type.
func (r CheckpointArtifact) Equal(other CheckpointArtifact) bool {
	a, b := labels.Merge(r.Labels), labels.Merge(other.Labels)
	return r.ID == other.ID && r.Tenant == other.Tenant && r.Deployment == other.Deployment &&
		r.Subject == other.Subject && r.ContextID == other.ContextID && r.TaskID == other.TaskID &&
		r.Version == other.Version && r.SHA256 == other.SHA256 && r.Size == other.Size &&
		slices.Equal(a.Subjects, b.Subjects) && slices.Equal(a.Workspaces, b.Workspaces) && slices.Equal(a.Taints, b.Taints)
}

// CheckpointGuard is an owner API, never access to the owner's storage.
// Operation IDs are generated by State, single-use, and protected by a State
// transaction lock before Pin. A lost acknowledgement must not remove pins.
type CheckpointGuard interface {
	PinCheckpointReferences(context.Context, contracts.Scope, string, []CheckpointArtifact) error
	ReleaseCheckpointReferences(context.Context, string) error
}

// CheckpointSettlement proves the original State transaction has finished.
// False or error means UNKNOWN, not permission to expire a pin.
type CheckpointSettlement func(context.Context, string) (bool, error)
